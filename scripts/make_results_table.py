#!/usr/bin/env python3
"""Build docs/results_table.md from result files only (no hand-typed numbers).

Validation AUC = mean over the 7 development walk-forward folds; Final Test AUC = pooled holdout AUC under the frozen
procedure; trading columns = holdout backtest at BASE cost with the frozen delta. Cells that were not
evaluated print as 'not evaluated'.
"""
from __future__ import annotations

import json
from pathlib import Path

import polars as pl

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "reports" / "tables"


def f(x, pct=False, nd=3):
    if x is None or (isinstance(x, float) and x != x):
        return "not evaluated"
    return f"{x * 100:.1f}%" if pct else f"{x:.{nd}f}"


def main() -> None:
    dev = pl.read_csv(T / "model_summary.csv")
    hold = pl.read_csv(T / "holdout" / "ablation.csv") if (T / "holdout" / "ablation.csv").exists() else None
    dev_econ = pl.read_csv(T / "dev_ablation_economics.csv")
    frozen = json.loads((T / "frozen_parameters.json").read_text())
    names = {"logit": "Logistic regression", "rf": "Random forest", "lgbm": "LightGBM"}
    lines = ["# Final results table", "",
             f"Primary (frozen) model: **{frozen['selection']['selected']}**, δ = {frozen['delta']}, base cost "
             "5.523 bps/side. Validation = development walk-forward (7 folds, 2024-03 → 2025-09); final test = "
             "untouched holdout 2025-10 → 2026-09 (frozen procedure). Generated by `scripts/make_results_table.py`.", "",
             "| Model | Feature set | Validation AUC (mean ± sd) | Dev OOF Sharpe gross / net | Final test AUC | Final tradable AUC | "
             "Final Sharpe gross | Final Sharpe net (base) | Final max DD net | Final net return | Break-even (bps/side) |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m in ("logit", "rf", "lgbm"):
        for fs in ("A_price", "B_price_volume", "C_plus_flow", "D_plus_book", "E_all"):
            d = dev.filter(pl.col("config") == f"{m}_{fs}_h15")
            e = dev_econ.filter(pl.col("config") == f"{m}_{fs}_h15")
            h = hold.filter((pl.col("model") == m) & (pl.col("fset") == fs)) if hold is not None else pl.DataFrame()
            hv = h.row(0, named=True) if h.height else {}
            star = " **(primary)**" if f"{m}_{fs}_h15" == frozen["selection"]["selected"] else ""
            lines.append(
                f"| {names[m]}{star} | {fs} | "
                f"{f(d['auc_mean'][0]) + ' ± ' + f(d['auc_sd'][0]) if d.height else 'not evaluated'} | "
                f"{f(e['sharpe_gross'][0], nd=2) + ' / ' + f(e['sharpe_base'][0], nd=2) if e.height else 'not evaluated'} | "
                f"{f(hv.get('auc'))} | {f(hv.get('tradable_auc'))} | {f(hv.get('sharpe_gross'), nd=2)} | "
                f"{f(hv.get('sharpe_base'), nd=2)} | {f(hv.get('max_dd_base'), pct=True)} | "
                f"{f(hv.get('total_return_base'), pct=True)} | {f(hv.get('breakeven_bps'), nd=2)} |")
    bt = pl.read_csv(T / "holdout" / "backtest_summary.csv") if (T / "holdout" / "backtest_summary.csv").exists() else None
    lines += ["", "## Benchmarks on the holdout (frozen rules)", "",
              "| Strategy | Cost | Total return | Sharpe | Max drawdown | Trades | Break-even (bps/side) |",
              "|---|---|---:|---:|---:|---:|---:|"]
    if bt is not None:
        for r in bt.filter(pl.col("cost").is_in(["gross", "base"])).sort("cost", "strategy").iter_rows(named=True):
            lines.append(f"| {r['strategy']} | {r['cost']} | {f(r['total_return'], pct=True)} | {f(r['sharpe'], nd=2)} | "
                         f"{f(r['max_drawdown'], pct=True)} | {r['n_trades']:,} | "
                         f"{f(r['breakeven_cost_bps_per_side'], nd=2) if r['strategy'] != 'buy_and_hold' else 'n/a'} |")
    (ROOT / "docs" / "results_table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
